def _b64(s):
    return base64.b64encode(s.encode()).decode()


def _hex(s):
    return s.encode().hex()


def _caesar(s, shift):
    out = []
    for ch in s:
        if ch.isalpha():
            a = ord("a") if ch.islower() else ord("A")
            out.append(chr((ord(ch) - a + shift) % 26 + a))
        else:
            out.append(ch)
    return "".join(out)


def _bin(s):
    return " ".join(f"{b:08b}" for b in s.encode())


